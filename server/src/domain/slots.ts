/**
 * Pure domain logic for slot generation and time zone handling.
 *
 * All slot generation works in UTC instants. Local times are used only
 * for display and for determining mentor working windows.
 *
 * Key invariants:
 * - Slots are generated from the parent's local calendar day boundaries
 * - Each slot is a UTC instant; DST gaps are naturally skipped
 * - Fall-back (repeated hours) produces two distinct UTC instants
 * - Mentor availability is checked by converting UTC instants to mentor local time
 */

import { DateTime, IANAZone } from 'luxon';
import type { IWorkingWindow } from '../models/Mentor.js';
import { getClock, type Clock } from '../utils/clock.js';

export interface SlotInfo {
  /** Slot start as ISO UTC string */
  startUtc: string;
  /** Slot end as ISO UTC string */
  endUtc: string;
  /** Slot start rendered in the parent's local time */
  localStart: string;
  /** Slot end rendered in the parent's local time */
  localEnd: string;
  /** Zone abbreviation at slot start in parent's timezone (e.g. "EST", "EDT") */
  tzAbbr: string;
  /** UTC offset string at slot start (e.g. "UTC−5") */
  utcOffset: string;
}

export interface SlotAvailability extends SlotInfo {
  available: boolean;
  limited: boolean;
}

/**
 * Validate that a string is a valid IANA timezone.
 */
export function isValidIANAZone(tz: string): boolean {
  return IANAZone.isValidZone(tz);
}

/**
 * Get the start and end of a calendar day in a given IANA timezone as UTC instants.
 *
 * For spring-forward days this returns a 23-hour window.
 * For fall-back days this returns a 25-hour window.
 */
export function getDayBoundsUtc(
  dateStr: string,
  tz: string
): { startUtc: DateTime; endUtc: DateTime } {
  // Parse as the start of the given date in the parent's timezone
  const dayStart = DateTime.fromISO(`${dateStr}T00:00:00`, { zone: tz });
  // The next day's start gives us the correct boundary even across DST
  const dayEnd = dayStart.plus({ days: 1 });

  return {
    startUtc: dayStart.toUTC(),
    endUtc: dayEnd.toUTC(),
  };
}

/**
 * Generate all slot start times (as UTC instants) within a parent's local calendar day.
 *
 * Slots are generated by iterating UTC instants at the configured interval,
 * starting from the UTC equivalent of the parent's local midnight.
 *
 * Spring-forward: the gap is naturally skipped because we iterate in UTC.
 * The local times that don't exist simply never appear.
 *
 * Fall-back: the repeated hour produces two distinct UTC instants which
 * map to the same local clock time but different zone abbreviations.
 */
export function generateSlotStartsUtc(
  dateStr: string,
  parentTz: string,
  intervalMinutes: number
): DateTime[] {
  const { startUtc, endUtc } = getDayBoundsUtc(dateStr, parentTz);
  const slots: DateTime[] = [];

  let current = startUtc;
  while (current < endUtc) {
    slots.push(current);
    current = current.plus({ minutes: intervalMinutes });
  }

  return slots;
}

/**
 * Convert a UTC instant to a local time display in the given timezone.
 */
export function utcToLocal(utcInstant: DateTime | Date, tz: string) {
  const dt =
    utcInstant instanceof Date
      ? DateTime.fromJSDate(utcInstant, { zone: 'utc' }).setZone(tz)
      : utcInstant.setZone(tz);

  return {
    localISO: dt.toISO()!,
    localFormatted: dt.toFormat('EEE, d MMM yyyy · h:mm a'),
    tzAbbr: dt.toFormat('ZZZZ'),
    utcOffset: formatUtcOffset(dt.offset),
    localDate: dt.toFormat('yyyy-MM-dd'),
    localTime: dt.toFormat('HH:mm'),
  };
}

/**
 * Format a UTC offset in minutes to a human-readable string like "UTC−5" or "UTC+5:30".
 */
export function formatUtcOffset(offsetMinutes: number): string {
  const sign = offsetMinutes >= 0 ? '+' : '−';
  const absMinutes = Math.abs(offsetMinutes);
  const hours = Math.floor(absMinutes / 60);
  const mins = absMinutes % 60;
  return mins > 0 ? `UTC${sign}${hours}:${String(mins).padStart(2, '0')}` : `UTC${sign}${hours}`;
}

/**
 * Build the full SlotInfo for a UTC slot start time in a parent's timezone.
 */
export function buildSlotInfo(
  slotStartUtc: DateTime,
  durationMinutes: number,
  parentTz: string
): SlotInfo {
  const slotEndUtc = slotStartUtc.plus({ minutes: durationMinutes });
  const localStart = utcToLocal(slotStartUtc.toJSDate(), parentTz);
  const localEnd = utcToLocal(slotEndUtc.toJSDate(), parentTz);

  return {
    startUtc: slotStartUtc.toUTC().toISO()!,
    endUtc: slotEndUtc.toUTC().toISO()!,
    localStart: `${localStart.localFormatted} ${localStart.tzAbbr} (${localStart.utcOffset})`,
    localEnd: `${localEnd.localFormatted} ${localEnd.tzAbbr} (${localEnd.utcOffset})`,
    tzAbbr: localStart.tzAbbr,
    utcOffset: localStart.utcOffset,
  };
}

/**
 * Check if a UTC instant falls within a mentor's working window.
 *
 * The working window is defined in the mentor's local time (e.g. IST).
 * Windows may cross midnight (e.g. 20:00–05:00 means 8pm to 5am next day).
 *
 * We convert the UTC instant to the mentor's local time, then check
 * if the local time falls within any of the working windows.
 */
export function isMentorWorkingAtUtc(
  slotStartUtc: DateTime | Date,
  mentorTz: string,
  workingWindows: IWorkingWindow[],
  slotDurationMinutes: number
): boolean {
  const dt =
    slotStartUtc instanceof Date
      ? DateTime.fromJSDate(slotStartUtc, { zone: 'utc' }).setZone(mentorTz)
      : slotStartUtc.setZone(mentorTz);

  const slotEnd = dt.plus({ minutes: slotDurationMinutes });
  const slotStartMinutes = dt.hour * 60 + dt.minute;
  const slotEndMinutes = slotEnd.hour * 60 + slotEnd.minute;

  for (const window of workingWindows) {
    const [wStartH, wStartM] = window.startLocal.split(':').map(Number);
    const [wEndH, wEndM] = window.endLocal.split(':').map(Number);
    const windowStart = wStartH * 60 + wStartM;
    const windowEnd = wEndH * 60 + wEndM;

    if (windowEnd > windowStart) {
      // Normal window (e.g. 15:00–24:00 or 09:00–17:00)
      // Slot must start AND end within the window
      if (slotStartMinutes >= windowStart && slotEndMinutes <= windowEnd) {
        return true;
      }
    } else {
      // Midnight-crossing window (e.g. 20:00–05:00)
      // The slot can be in the "before midnight" part OR the "after midnight" part
      // But the entire slot (start to end) must fit in one contiguous segment

      // Check if slot is entirely in the evening part (windowStart..midnight)
      if (slotStartMinutes >= windowStart) {
        // Slot starts in the evening part
        if (slotEndMinutes <= windowEnd || slotEndMinutes > slotStartMinutes) {
          // Slot ends before window end (after midnight) or still before midnight
          return true;
        }
      }

      // Check if slot is entirely in the morning part (midnight..windowEnd)
      if (slotStartMinutes < windowEnd && slotEndMinutes <= windowEnd) {
        return true;
      }
    }
  }

  return false;
}

/**
 * Get the mentor's local calendar date for a given UTC instant.
 * This is critical for capacity counting — a US evening slot may land
 * on the next IST calendar day.
 */
export function getMentorLocalDate(slotStartUtc: DateTime | Date, mentorTz: string): string {
  const dt =
    slotStartUtc instanceof Date
      ? DateTime.fromJSDate(slotStartUtc, { zone: 'utc' }).setZone(mentorTz)
      : slotStartUtc.setZone(mentorTz);

  return dt.toFormat('yyyy-MM-dd');
}

function resolveNow(nowOrClock?: DateTime | Clock): DateTime {
  if (!nowOrClock) return getClock().now();
  if ('now' in nowOrClock && typeof (nowOrClock as Clock).now === 'function') {
    return (nowOrClock as Clock).now();
  }
  return nowOrClock as DateTime;
}

/**
 * Check if a slot start time satisfies the minimum lead time requirement.
 */
export function isSlotBookable(
  slotStartUtc: DateTime | Date,
  minLeadTimeHours: number,
  now?: DateTime | Clock
): boolean {
  const nowUtc = resolveNow(now);
  const slotDt =
    slotStartUtc instanceof Date
      ? DateTime.fromJSDate(slotStartUtc, { zone: 'utc' })
      : slotStartUtc.toUTC();

  const minStart = nowUtc.plus({ hours: minLeadTimeHours });
  return slotDt >= minStart;
}

/**
 * Check if a date string is within the bookable window (today + N days).
 */
export function isDateInBookableWindow(
  dateStr: string,
  parentTz: string,
  bookableWindowDays: number,
  now?: DateTime | Clock
): boolean {
  const nowLocal = resolveNow(now).setZone(parentTz);
  const todayStr = nowLocal.toFormat('yyyy-MM-dd');
  const maxDate = nowLocal.plus({ days: bookableWindowDays }).toFormat('yyyy-MM-dd');

  return dateStr >= todayStr && dateStr <= maxDate;
}

/**
 * Group time slots into Morning/Afternoon/Evening buckets based on parent's local time.
 */
export type TimeOfDay = 'morning' | 'afternoon' | 'evening';

export function getTimeOfDay(slotStartUtc: DateTime | Date, parentTz: string): TimeOfDay {
  const dt =
    slotStartUtc instanceof Date
      ? DateTime.fromJSDate(slotStartUtc, { zone: 'utc' }).setZone(parentTz)
      : slotStartUtc.setZone(parentTz);

  const hour = dt.hour;
  if (hour < 12) return 'morning';
  if (hour < 17) return 'afternoon';
  return 'evening';
}

